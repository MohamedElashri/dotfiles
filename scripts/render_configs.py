#!/usr/bin/env python3
"""Render platform preferences and the manifest's shell plugin selection."""
import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def render(check=False):
    base = ROOT / 'config/terminals/waveterm'
    common = json.loads((base / 'settings.common.json').read_text())
    outputs = {'linux': base / 'config/settings.json',
               'mac': ROOT / 'config/mac/waveterm/config/settings.json'}
    stale = []
    for platform, target in outputs.items():
        settings = dict(common, **json.loads((base / f'settings.{platform}.json').read_text()))
        content = json.dumps(settings, indent=2) + '\n'
        if not target.exists() or target.read_text() != content:
            stale.append(target.relative_to(ROOT))
            if not check:
                target.write_text(content)
    plugin_groups = json.loads((ROOT / 'setup/assets.json').read_text())['shell_plugins']
    for names in plugin_groups.values():
        if any(not re.fullmatch(r'[A-Za-z0-9_-]+', name) for name in names):
            raise ValueError('Invalid shell plugin name in assets.json')
    content = '# Generated by dotfiles render from setup/assets.json.\n'
    content += 'DOTFILES_OMZ_PLUGINS=(' + ' '.join(plugin_groups['common']) + ')\n'
    content += 'case "$(uname -s)" in\n'
    for platform, system in [('mac', 'Darwin'), ('linux', 'Linux')]:
        content += f'  {system}) DOTFILES_OMZ_PLUGINS+=(' + ' '.join(plugin_groups[platform]) + ') ;;\n'
    content += 'esac\n'
    content += 'if (( ${+DOTFILES_EXTRA_OMZ_PLUGINS} )); then\n'
    content += '  DOTFILES_OMZ_PLUGINS+=("${DOTFILES_EXTRA_OMZ_PLUGINS[@]}")\nfi\n'
    content += 'DOTFILES_OMZ_PLUGINS+=(' + ' '.join(plugin_groups['last']) + ')\n'
    target = ROOT / 'zsh/plugins.zsh'
    if not target.exists() or target.read_text() != content:
        stale.append(target.relative_to(ROOT))
        if not check:
            target.write_text(content)
    return stale


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    stale = render(args.check)
    for path in stale:
        print(f'{"Stale" if args.check else "Rendered"}: {path}')
    raise SystemExit(1 if args.check and stale else 0)
